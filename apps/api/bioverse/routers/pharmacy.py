# --- Adherence -------------------------------------------------------------------------------


def adherence_stats(taken: set[date], start: date | None, today: date) -> dict:
    """Patient-logged adherence. Today counts only once it's logged, so an unfinished day isn't a miss.

    Days before tracking started (first pickup) are excluded from every window.
    """
    if start is None:
        return {"tracking": False, "pct_7": None, "pct_30": None, "taken_7": 0, "days_7": 0, "taken_30": 0,
                "days_30": 0, "streak": 0, "taken_today": False}
    taken_today = today in taken

    def window(n: int) -> tuple[int, int]:
        # The last n days, ending today once today's dose is logged, otherwise ending yesterday.
        last = today if taken_today else today - timedelta(days=1)
        first = max(start, last - timedelta(days=n - 1))
        if last < first:
            return 0, 0
        days = (last - first).days + 1
        hits = sum(1 for d in taken if first <= d <= last)
        return hits, days

    def pct(hits: int, days: int) -> int | None:
        return None if days == 0 else (200 * hits + days) // (2 * days)

    t7, d7 = window(7)
    t30, d30 = window(30)
    streak = 0
    d = today if taken_today else today - timedelta(days=1)
    while d in taken and d >= start:
        streak += 1
        d -= timedelta(days=1)
    return {"tracking": True, "pct_7": pct(t7, d7), "pct_30": pct(t30, d30), "taken_7": t7, "days_7": d7,
            "taken_30": t30, "days_30": d30, "streak": streak, "taken_today": taken_today}


def _tracking_start(conn: Connection, rx_id: str, tz) -> date | None:
    row = conn.execute(
        "SELECT min(picked_up_at) AS at FROM medication_dispenses WHERE medication_request_id = %s AND picked_up_at IS NOT NULL",
        (rx_id,),
    ).fetchone()
    return row["at"].astimezone(tz).date() if row and row["at"] else None


def adherence_for(conn: Connection, rx_id: str) -> dict:
    ctx = SeedContext()
    today = ctx.today
    start = _tracking_start(conn, rx_id, ctx.tz)
    logs = conn.execute(
        "SELECT taken_on FROM medication_adherence_logs WHERE medication_request_id = %s AND taken_on > %s",
        (rx_id, today - timedelta(days=60)),
    ).fetchall()
    taken = {r["taken_on"] for r in logs}
    stats = adherence_stats(taken, start, today)
    stats["started_on"] = start
    stats["days"] = [
        {"date": today - timedelta(days=i), "taken": (today - timedelta(days=i)) in taken,
         "tracked": start is not None and today - timedelta(days=i) >= start}
        for i in range(13, -1, -1)
    ]
    stats["target_pct"] = ADHERENCE_TARGET
    return stats


