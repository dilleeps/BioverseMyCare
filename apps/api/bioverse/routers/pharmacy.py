# --- Fills (demo pharmacy) -------------------------------------------------------------------


def _load_fill(conn: Connection, user: User, dispense_id: str) -> dict:
    row = conn.execute(
        """
        SELECT d.id::text, d.status, d.patient_id::text, d.medication_request_id::text, m.drug_name, m.strength
        FROM medication_dispenses d JOIN medication_requests m ON m.id = d.medication_request_id
        WHERE d.id::text = %s FOR UPDATE OF d
        """,
        (dispense_id,),
    ).fetchone()
    if row is None or row["patient_id"] != user.patient_id:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Fill not found")
    return row


NEXT_FILL_STATUS = {"sent": "received", "received": "ready"}


@router.post("/fills/{dispense_id}/simulate-update")
def simulate_pharmacy_update(dispense_id: str, conn: Conn, user: Patient) -> dict:
    """Demo only: stands in for the pharmacy's status message (sent -> received -> ready)."""
    fill = _load_fill(conn, user, dispense_id)
    nxt = NEXT_FILL_STATUS.get(fill["status"])
    if nxt is None:
        raise HTTPException(status.HTTP_409_CONFLICT, "The pharmacy has nothing more to update on this fill")
    conn.execute(
        "UPDATE medication_dispenses SET status = %s, ready_at = CASE WHEN %s = 'ready' THEN now() ELSE ready_at END WHERE id::text = %s",
        (nxt, nxt, dispense_id),
    )
    audit.record(conn, action=f"fill_{nxt}", entity_type="medication_dispense", entity_id=dispense_id, actor=user,
                 agent="demo-pharmacy", patient_id=user.patient_id)
    return {"id": dispense_id, "status": nxt}


