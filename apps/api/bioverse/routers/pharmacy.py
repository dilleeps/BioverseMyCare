class RefillIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    note: str | None = Field(default=None, max_length=500)


def _new_fill(conn: Connection, rx: dict, pharmacy_id: str) -> str:
    n = conn.execute(
        "SELECT coalesce(max(fill_number), 0) + 1 AS n FROM medication_dispenses WHERE medication_request_id = %s",
        (rx["id"],),
    ).fetchone()["n"]
    return conn.execute(
        """
        INSERT INTO medication_dispenses (medication_request_id, patient_id, pharmacy_id, fill_number, status)
        VALUES (%s, %s, %s, %s, 'sent') RETURNING id::text
        """,
        (rx["id"], rx["patient_id"], pharmacy_id, n),
    ).fetchone()["id"]


@router.post("/prescriptions/{rx_id}/refill-requests", status_code=status.HTTP_201_CREATED)
def request_refill(rx_id: str, body: RefillIn, conn: Conn, user: Patient) -> dict:
    rx = _load_rx(conn, user, rx_id, lock=True)
    if rx["status"] != "active":
        raise HTTPException(
            status.HTTP_409_CONFLICT,
            {"code": "not_active", "message": "This prescription isn't active. Message your care team if you still need it."},
        )
    if rx["pending_refill_id"]:
        raise HTTPException(status.HTTP_409_CONFLICT,
                            {"code": "pending", "message": "A refill request is already waiting for your prescriber."})
    if rx["dispense_status"] in ("sent", "received", "ready"):
        raise HTTPException(
            status.HTTP_409_CONFLICT,
            {"code": "fill_in_progress",
             "message": "Your last fill is still in progress or waiting for pickup at the pharmacy."},
        )
    preferred = _preferred(conn, rx["patient_id"])
    pharmacy_id = preferred["id"] if preferred else rx["pharmacy_id"]
    if not pharmacy_id:
        raise HTTPException(status.HTTP_409_CONFLICT,
                            {"code": "no_pharmacy", "message": "Choose a pharmacy first."})
    note = (body.note or "").strip() or None
    label = f"{rx['drug_name']} {rx['strength']}"

    if rx["refills_remaining"] > 0:
        dispense_id = _new_fill(conn, rx, pharmacy_id)
        conn.execute("UPDATE medication_requests SET refills_remaining = refills_remaining - 1 WHERE id::text = %s", (rx_id,))
        req = conn.execute(
            """
            INSERT INTO refill_requests (medication_request_id, patient_id, prescriber_id, pharmacy_id, status,
                                         patient_note, dispense_id)
            VALUES (%s, %s, %s, %s, 'sent_to_pharmacy', %s, %s) RETURNING id::text, status, created_at
            """,
            (rx_id, rx["patient_id"], rx["prescriber_id"], pharmacy_id, note, dispense_id),
        ).fetchone()
        audit.record(conn, action="refill_sent_to_pharmacy", entity_type="refill_request", entity_id=req["id"],
                     actor=user, patient_id=rx["patient_id"],
                     detail={"medication_request_id": rx_id, "dispense_id": dispense_id,
                             "refills_remaining": rx["refills_remaining"] - 1})
        return {**req, "requires_approval": False, "dispense_id": dispense_id,
                "message": f"Sent to the pharmacy. {rx['refills_remaining'] - 1} refills left after this one."}

    req = conn.execute(
        """
        INSERT INTO refill_requests (medication_request_id, patient_id, prescriber_id, pharmacy_id, status, patient_note)
        VALUES (%s, %s, %s, %s, 'pending_approval', %s) RETURNING id::text, status, created_at
        """,
        (rx_id, rx["patient_id"], rx["prescriber_id"], pharmacy_id, note),
    ).fetchone()
    body_text = f"No refills remaining on {label} ({rx['sig']})."
    if note:
        body_text += f" Patient note: \"{note}\""
    item = conn.execute(
        """
        INSERT INTO review_items (kind, patient_id, practitioner_id, ref_id, title, body, priority, link)
        VALUES ('refill_request', %s, %s, %s, %s, %s, 'routine', '/clinician/refills') RETURNING id::text
        """,
        (rx["patient_id"], rx["prescriber_id"], req["id"], f"Refill request · {label}", body_text),
    ).fetchone()
    conn.execute("UPDATE refill_requests SET review_item_id = %s WHERE id = %s", (item["id"], req["id"]))
    audit.record(conn, action="refill_requested", entity_type="refill_request", entity_id=req["id"], actor=user,
                 patient_id=rx["patient_id"], detail={"medication_request_id": rx_id, "review_item_id": item["id"]})
    return {**req, "requires_approval": True, "dispense_id": None,
            "message": f"No refills are left, so we've asked {rx['prescriber_name']} to approve it. "
                       "You'll see the answer here."}


REFILL_QUEUE_SELECT = """
    SELECT r.id::text, r.status, r.patient_note, r.decision_note, r.decided_at, r.created_at,
           r.review_item_id::text, p.id::text AS patient_id, p.name AS patient_name, p.birth_date,
           m.id::text AS medication_request_id, m.drug_code, m.drug_name, m.strength, m.sig, m.quantity,
           m.refills_authorized, m.refills_remaining, m.authored_at, ph.name AS pharmacy_name
    FROM refill_requests r
    JOIN patients p ON p.id = r.patient_id
    JOIN medication_requests m ON m.id = r.medication_request_id
    JOIN pharmacies ph ON ph.id = r.pharmacy_id
"""


@router.get("/clinician/refill-requests")
def refill_queue(conn: Conn, user: Clinician,
                 status_filter: Literal["pending_approval", "decided", "all"] = "pending_approval") -> list[dict]:
    rows = conn.execute(
        REFILL_QUEUE_SELECT + """
        WHERE r.prescriber_id = %(pr)s AND p.organization_id = %(org)s
          AND r.status IN ('pending_approval', 'approved', 'denied')
          AND (%(f)s = 'all' OR (%(f)s = 'pending_approval' AND r.status = 'pending_approval')
               OR (%(f)s = 'decided' AND r.status IN ('approved', 'denied')))
        ORDER BY (r.status = 'pending_approval') DESC, r.created_at DESC
        LIMIT 100
        """,
        {"pr": user.practitioner_id, "org": user.organization_id, "f": status_filter},
    ).fetchall()
    for r in rows:
        r["adherence"] = adherence_for(conn, r["medication_request_id"])
        r["interactions"] = interactions_for(conn, r["patient_id"])["warnings"]
    return rows


class RefillDecisionIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    decision: Literal["approve", "deny"]
    note: str | None = Field(default=None, max_length=1000)
    additional_refills: StrictInt = Field(default=0, ge=0, le=11)


@router.post("/clinician/refill-requests/{request_id}/decision")
def decide_refill(request_id: str, body: RefillDecisionIn, conn: Conn, user: Clinician) -> dict:
    req = conn.execute(
        """
        SELECT r.id::text, r.status, r.patient_id::text, r.prescriber_id::text, r.pharmacy_id::text,
               r.review_item_id::text, r.medication_request_id::text
        FROM refill_requests r WHERE r.id::text = %s FOR UPDATE
        """,
        (request_id,),
    ).fetchone()
    if req is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Refill request not found")
    assert_patient_access(conn, user, req["patient_id"])
    if req["prescriber_id"] != user.practitioner_id:
        raise HTTPException(status.HTTP_403_FORBIDDEN, "Only the prescriber can decide this refill")
    if req["status"] != "pending_approval":
        raise HTTPException(status.HTTP_409_CONFLICT, "This refill request has already been decided")
    note = (body.note or "").strip() or None
    if body.decision == "deny" and not note:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "Add a note for the patient explaining the denial")
    if body.decision == "deny" and body.additional_refills:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "Refills can only be added when approving")

    rx = conn.execute(
        "SELECT id::text, patient_id::text, status, drug_name, strength FROM medication_requests WHERE id = %s FOR UPDATE",
        (req["medication_request_id"],),
    ).fetchone()
    dispense_id = None
    if body.decision == "approve":
        if rx["status"] != "active":
            raise HTTPException(status.HTTP_409_CONFLICT, "The prescription is no longer active")
        dispense_id = _new_fill(conn, rx, req["pharmacy_id"])
        conn.execute(
            """
            UPDATE medication_requests
            SET refills_authorized = refills_authorized + 1 + %s, refills_remaining = refills_remaining + %s
            WHERE id = %s
            """,
            (body.additional_refills, body.additional_refills, rx["id"]),
        )
    new_status = "approved" if body.decision == "approve" else "denied"
    conn.execute(
        """
        UPDATE refill_requests SET status = %s, decision_note = %s, decided_by = %s, decided_at = now(), dispense_id = %s
        WHERE id::text = %s
        """,
        (new_status, note, user.id, dispense_id, request_id),
    )
    if req["review_item_id"]:
        resolution = f"refill_{new_status}" + (f": {note}" if note else "")
        conn.execute(
            """
            UPDATE review_items SET status = 'resolved', resolution = %s, resolved_by = %s, resolved_at = now()
            WHERE id = %s AND status = 'open'
            """,
            (resolution, user.id, req["review_item_id"]),
        )
    audit.record(conn, action=f"refill_{new_status}", entity_type="refill_request", entity_id=request_id, actor=user,
                 patient_id=req["patient_id"],
                 detail={"medication_request_id": rx["id"], "dispense_id": dispense_id,
                         "additional_refills": body.additional_refills, "review_item_id": req["review_item_id"]})
    return {"id": request_id, "status": new_status, "dispense_id": dispense_id, "decision_note": note}


