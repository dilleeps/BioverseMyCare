RX_SELECT = """
    SELECT m.id::text, m.patient_id::text, m.drug_code, m.drug_name, m.strength, m.sig, m.quantity,
           m.refills_authorized, m.refills_remaining, m.status, m.authored_at,
           pr.id::text AS prescriber_id, pr.name AS prescriber_name,
           ph.id::text AS pharmacy_id, ph.name AS pharmacy_name,
           d.id::text AS dispense_id, d.status AS dispense_status, d.fill_number, d.sent_at, d.ready_at,
           d.picked_up_at, dph.name AS dispense_pharmacy_name, dph.phone AS dispense_pharmacy_phone,
           (SELECT r.id::text FROM refill_requests r WHERE r.medication_request_id = m.id AND r.status = 'pending_approval')
               AS pending_refill_id
    FROM medication_requests m
    JOIN practitioners pr ON pr.id = m.prescriber_id
    LEFT JOIN pharmacies ph ON ph.id = m.pharmacy_id
    LEFT JOIN LATERAL (
        SELECT * FROM medication_dispenses x WHERE x.medication_request_id = m.id ORDER BY x.fill_number DESC LIMIT 1
    ) d ON true
    LEFT JOIN pharmacies dph ON dph.id = d.pharmacy_id
"""


def _rx_out(conn: Connection, row: dict) -> dict:
    row["latest_fill"] = None
    if row["dispense_id"]:
        row["latest_fill"] = {
            "id": row["dispense_id"], "status": row["dispense_status"], "fill_number": row["fill_number"],
            "sent_at": row["sent_at"], "ready_at": row["ready_at"], "picked_up_at": row["picked_up_at"],
            "pharmacy_name": row["dispense_pharmacy_name"], "pharmacy_phone": row["dispense_pharmacy_phone"],
        }
    for k in ("dispense_id", "fill_number", "sent_at", "ready_at", "picked_up_at", "dispense_pharmacy_name",
              "dispense_pharmacy_phone"):
        row.pop(k)
    row["adherence"] = adherence_for(conn, row["id"]) if row["status"] == "active" else None
    row["last_refill_request"] = conn.execute(
        """
        SELECT id::text, status, decision_note, decided_at, created_at FROM refill_requests
        WHERE medication_request_id = %s ORDER BY created_at DESC LIMIT 1
        """,
        (row["id"],),
    ).fetchone()
    return row


@router.get("/prescriptions")
def list_prescriptions(conn: Conn, user: CurrentUser, patient_id: str | None = None) -> dict:
    pid = _patient_scope(conn, user, patient_id)
    rows = conn.execute(
        RX_SELECT + """
        WHERE m.patient_id = %s
        ORDER BY (m.status IN ('active', 'on_hold')) DESC, m.authored_at DESC
        """,
        (pid,),
    ).fetchall()
    audit.record(conn, action="prescriptions_viewed", entity_type="medication_request", actor=user, patient_id=pid)
    return {"prescriptions": [_rx_out(conn, r) for r in rows], "notice": DEMO_PHARMACY_NOTICE}


def _load_rx(conn: Connection, user: User, rx_id: str, lock: bool = False) -> dict:
    if lock:
        conn.execute("SELECT 1 FROM medication_requests WHERE id::text = %s FOR UPDATE", (rx_id,))
    row = conn.execute(RX_SELECT + " WHERE m.id::text = %s", (rx_id,)).fetchone()
    if row is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Prescription not found")
    _patient_scope(conn, user, row["patient_id"])
    return row


