def interactions_for(conn: Connection, patient_id: str, candidate: str | None = None) -> dict:
    """Curated pairs among the patient's active medicines (plus an optional candidate drug)."""
    active = conn.execute(
        "SELECT DISTINCT drug_code, drug_name FROM medication_requests WHERE patient_id = %s AND status = 'active'",
        (patient_id,),
    ).fetchall()
    names = {r["drug_code"]: r["drug_name"] for r in active}
    codes = set(names)
    if candidate:
        cand = conn.execute("SELECT code, name FROM drug_monographs WHERE code = %s", (candidate,)).fetchone()
        if cand is None:
            raise HTTPException(status.HTTP_404_NOT_FOUND, "That medicine isn't in the demo interaction list")
        names.setdefault(cand["code"], cand["name"])
    check = codes | ({candidate} if candidate else set())
    rows = conn.execute(
        """
        SELECT i.id::text, i.drug_a, i.drug_b, i.substance, i.severity, i.summary, i.advice,
               a.name AS drug_a_name, b.name AS drug_b_name
        FROM drug_interactions i
        JOIN drug_monographs a ON a.code = i.drug_a
        LEFT JOIN drug_monographs b ON b.code = i.drug_b
        WHERE (i.drug_b IS NOT NULL AND i.drug_a = ANY(%(c)s) AND i.drug_b = ANY(%(c)s))
           OR (i.drug_b IS NULL AND i.drug_a = ANY(%(c)s))
        """,
        {"c": list(check)},
    ).fetchall()
    warnings = []
    order = {"major": 0, "moderate": 1, "advisory": 2}
    for r in rows:
        pair = {r["drug_a"], r["drug_b"]} if r["drug_b"] else {r["drug_a"]}
        warnings.append({
            "id": r["id"],
            "kind": "drug" if r["drug_b"] else "food",
            "severity": r["severity"],
            "between": [r["drug_a_name"], r["drug_b_name"] or r["substance"]],
            "involves_candidate": bool(candidate and candidate in pair),
            "summary": r["summary"],
            "advice": r["advice"],
        })
    warnings.sort(key=lambda w: (order[w["severity"]], w["between"]))
    return {"checked": sorted(names[c] for c in check if c in names), "warnings": warnings,
            "notice": INTERACTION_NOTICE, "source": "Bioverse curated demo interaction list"}


@router.get("/interactions")
def check_interactions(conn: Conn, user: CurrentUser, patient_id: str | None = None, candidate: str | None = None) -> dict:
    pid = _patient_scope(conn, user, patient_id)
    out = interactions_for(conn, pid, candidate)
    audit.record(conn, action="interactions_checked", entity_type="medication_request", actor=user, patient_id=pid,
                 detail={"candidate": candidate, "warnings": len(out["warnings"])})
    return out
