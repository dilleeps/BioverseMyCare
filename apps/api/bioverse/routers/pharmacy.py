def _monograph(conn: Connection, code: str) -> dict | None:
    row = conn.execute(
        """
        SELECT code, name, drug_class, uses, how_to_take, common_side_effects, call_doctor_if
        FROM drug_monographs WHERE code = %s
        """,
        (code,),
    ).fetchone()
    if row:
        row["notice"] = DRUG_INFO_NOTICE
        row["source"] = "Bioverse demo monograph (curated)"
    return row


